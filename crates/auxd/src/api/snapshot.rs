/// Query for [`read_activity`].
#[derive(Debug, Clone, Copy)]
pub struct ActivityQuery<'a> {
    /// Only entries attributed to this agent.
    pub agent: Option<&'a str>,
    /// Time bound: `YYYY-MM-DD`, `YYYY-MM-DD HH:MM:SS`, or `30m`/`2h`/`7d`.
    pub since: Option<&'a str>,
    /// Maximum number of entries (already validated by the caller).
    pub limit: i64,
}

/// Why an activity read failed.
#[derive(Debug, thiserror::Error)]
pub enum ActivityReadError {
    /// The `since` value is not one of the documented forms.
    #[error("invalid since `{input}`")]
    Since {
        /// The offending value.
        input: String,
    },
    /// Anything else (store open/read failure).
    #[error(transparent)]
    Other(#[from] anyhow::Error),
}

/// Why a thread lookup failed.
#[derive(Debug, thiserror::Error)]
pub enum ThreadError {
    /// The path segment is not a safe agent name.
    #[error("invalid agent name `{agent}`: {reason}")]
    InvalidAgent {
        /// The offending name.
        agent: String,
        /// Why it was rejected.
        reason: String,
    },
    /// Anything else (store open/read failure).
    #[error(transparent)]
    Other(#[from] anyhow::Error),
}

/// Why a usage read failed.
#[derive(Debug, thiserror::Error)]
pub enum UsageReadError {
    /// The `day` value is not a valid calendar date.
    #[error("invalid day `{day}`")]
    InvalidDay {
        /// The offending value.
        day: String,
    },
    /// Anything else (store open/read failure).
    #[error(transparent)]
    Other(#[from] anyhow::Error),
}

/// What a `threads/:id` path segment points at.
#[derive(Debug, Clone)]
pub enum ThreadTarget {
    /// An explicit store session id.
    Session(SessionJson),
    /// An agent name: reads use its latest session, turns create a new one.
    Agent {
        /// The agent.
        name: String,
        /// Latest session, when the agent has any.
        latest: Option<SessionJson>,
    },
}

impl ThreadTarget {
    /// Agent this target resolves to.
    pub fn agent_name(&self) -> &str {
        match self {
            ThreadTarget::Session(session) => &session.agent,
            ThreadTarget::Agent { name, .. } => name,
        }
    }
}

