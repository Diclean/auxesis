/// Cheap monotonic fingerprint of everything [`agents_snapshot`] reads.
///
/// The 1 s WS poller compares two stamps and skips the full snapshot (and the
/// per-agent re-serialisation) when nothing changed. Store-side it is a handful
/// of aggregate queries over the small tables plus `MAX(id)` on the
/// insert-only ones; file-level inputs that live outside SQLite (config,
/// STOP, agent directories) are stamped too, as is the local day (usage
/// "today" rolls over without any write).
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct StoreChangeStamp {
    events: i64,
    messages: i64,
    sessions: (i64, String),
    jobs: (i64, String),
    usage: (i64, i64),
    runs: (i64, i64),
    config: Option<(u64, u64)>,
    stop: bool,
    agents_dir: Option<u64>,
    day: String,
}

pub(crate) fn change_stamp(home: &Path) -> StoreChangeStamp {
    let file_stamp = |path: &Path| {
        std::fs::metadata(path).ok().map(|meta| {
            let millis = meta
                .modified()
                .ok()
                .and_then(|time| time.duration_since(std::time::UNIX_EPOCH).ok())
                .map(|duration| duration.as_millis() as u64)
                .unwrap_or(0);
            (millis, meta.len())
        })
    };
    let config = file_stamp(&config_path(home));
    let agents_dir = file_stamp(&home.join("agents")).map(|(millis, _len)| millis);
    let stop = killswitch::is_stopped(home);

    let mut stamp = StoreChangeStamp {
        events: 0,
        messages: 0,
        sessions: (0, String::new()),
        jobs: (0, String::new()),
        usage: (0, 0),
        runs: (0, 0),
        config,
        stop,
        agents_dir,
        day: String::new(),
    };
    if let Ok(Some(conn)) = open_read_only(home) {
        stamp.events = max_id(&conn, "events").unwrap_or(0);
        stamp.messages = max_id(&conn, "messages").unwrap_or(0);
        stamp.sessions = grouped(
            &conn,
            "sessions",
            "id || ':' || agent || ':' || COALESCE(title, '') || ':' || updated_at",
        )
        .unwrap_or_default();
        stamp.jobs = grouped(
            &conn,
            "jobs",
            "id || ':' || agent || ':' || name || ':' || schedule || ':' || enabled \
             || ':' || COALESCE(next_run_at, '') || ':' || COALESCE(last_run_at, '') \
             || ':' || COALESCE(payload, '')",
        )
        .unwrap_or_default();
        stamp.usage = count_and_max_id(&conn, "usage").unwrap_or_default();
        stamp.runs = (
            count_where(&conn, "runs", "").unwrap_or(0),
            count_where(&conn, "runs", "status = 'running'").unwrap_or(0),
        );
        stamp.day = conn
            .query_row("SELECT date('now', 'localtime')", [], |row| row.get(0))
            .unwrap_or_default();
    }
    stamp
}

fn max_id(conn: &Connection, table: &str) -> anyhow::Result<i64> {
    if !table_exists(conn, table)? {
        return Ok(0);
    }
    let id: i64 = conn.query_row(
        &format!("SELECT COALESCE(MAX(id), 0) FROM {table}"),
        [],
        |row| row.get(0),
    )?;
    Ok(id)
}

fn count_and_max_id(conn: &Connection, table: &str) -> anyhow::Result<(i64, i64)> {
    if !table_exists(conn, table)? {
        return Ok((0, 0));
    }
    let row: (i64, i64) = conn.query_row(
        &format!("SELECT COUNT(*), COALESCE(MAX(id), 0) FROM {table}"),
        [],
        |row| Ok((row.get(0)?, row.get(1)?)),
    )?;
    Ok(row)
}

fn count_where(conn: &Connection, table: &str, predicate: &str) -> anyhow::Result<i64> {
    if !table_exists(conn, table)? {
        return Ok(0);
    }
    let where_clause = if predicate.is_empty() {
        String::new()
    } else {
        format!(" WHERE {predicate}")
    };
    let count: i64 = conn.query_row(
        &format!("SELECT COUNT(*) FROM {table}{where_clause}"),
        [],
        |row| row.get(0),
    )?;
    Ok(count)
}

/// `(row count, one concatenated row per entry)`: catches inserts, deletes
/// and updates (including same-length text edits) on the small tables.
fn grouped(conn: &Connection, table: &str, expr: &str) -> anyhow::Result<(i64, String)> {
    if !table_exists(conn, table)? {
        return Ok((0, String::new()));
    }
    let row: (i64, String) = conn.query_row(
        &format!("SELECT COUNT(*), COALESCE(GROUP_CONCAT({expr}, '|'), '') FROM {table}"),
        [],
        |row| Ok((row.get(0)?, row.get(1)?)),
    )?;
    Ok(row)
}

