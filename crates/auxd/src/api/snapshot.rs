/// `aux usage` semantics plus cap-only agents (the UI budget view needs both).
pub fn usage_snapshot(
    home: &Path,
    agent: Option<&str>,
    day: Option<&str>,
) -> Result<UsageResponse, UsageReadError> {
    let config = load_config(home);
    let connection = open_read_only(home)?;
    let (conn, day) = match (&connection, day) {
        (Some(conn), Some(day)) => {
            if !valid_day(conn, day)? {
                return Err(UsageReadError::InvalidDay {
                    day: day.to_string(),
                });
            }
            (Some(conn), day.to_string())
        }
        (Some(conn), None) => {
            let day: String = conn
                .query_row("SELECT date('now', 'localtime')", [], |row| row.get(0))
                .map_err(anyhow::Error::from)?;
            (Some(conn), day)
        }
        // No store yet: still answer with zeros for the requested day.
        (None, Some(day)) => {
            if !valid_day_offline(day) {
                return Err(UsageReadError::InvalidDay {
                    day: day.to_string(),
                });
            }
            (None, day.to_string())
        }
        (None, None) => (None, chrono::Local::now().format("%Y-%m-%d").to_string()),
    };

    let names: Vec<String> = match agent {
        Some(agent) => vec![agent.to_string()],
        None => {
            let mut names: BTreeSet<String> = match conn {
                Some(conn) => read_usage_agents(conn, &day)?.into_iter().collect(),
                None => BTreeSet::new(),
            };
            names.extend(config.budgets.agents.keys().cloned());
            names.into_iter().collect()
        }
    };

    let mut total = UsageTotals::default();
    let mut agents = Vec::new();
    for name in names {
        let totals = match conn {
            Some(conn) => read_usage_totals(conn, &name, &day)?,
            None => UsageTotals::default(),
        };
        let caps = config.budgets.caps_for(&name);
        if agent.is_none() && caps.is_unset() && totals.is_zero() {
            continue;
        }
        total.tokens_in += totals.tokens_in;
        total.tokens_out += totals.tokens_out;
        total.usd_cents += totals.usd_cents;
        agents.push(UsageAgentJson {
            agent: clean_field(&name),
            totals: totals.into(),
            caps: CapsJson {
                tokens_in: caps.limit(UsageKind::TokensIn),
                tokens_out: caps.limit(UsageKind::TokensOut),
                usd_cents: caps.limit(UsageKind::UsdCents),
            },
        });
    }
    Ok(UsageResponse {
        day,
        period: "day",
        agents,
        total: total.into(),
    })
}

/// True when `day` is a calendar date SQLite round-trips (`Store::valid_day`).
fn valid_day(conn: &Connection, day: &str) -> anyhow::Result<bool> {
    let matches: i64 =
        conn.query_row("SELECT COALESCE(date(?1) = ?1, 0)", [day], |row| row.get(0))?;
    Ok(matches == 1)
}

/// The same calendar check without a store (used before the store exists).
fn valid_day_offline(day: &str) -> bool {
    chrono::NaiveDate::parse_from_str(day, "%Y-%m-%d")
        .map(|date| date.format("%Y-%m-%d").to_string() == day)
        .unwrap_or(false)
}

