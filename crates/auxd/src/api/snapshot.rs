/// Read the merged timeline from the store at `home`, newest `limit` entries.
///
/// Never creates or migrates anything; a missing store is an empty timeline.
pub fn read_activity(
    home: &Path,
    query: ActivityQuery<'_>,
) -> Result<Vec<ActivityJson>, ActivityReadError> {
    let since = query.since.map(parse_since).transpose()?;

    let Some(conn) = open_read_only(home)? else {
        return Ok(Vec::new());
    };
    let mut entries = read_events(home, &conn, query.agent, since.as_ref(), query.limit)?;
    entries.extend(read_messages(
        home,
        &conn,
        query.agent,
        since.as_ref(),
        query.limit,
    )?);

    entries.sort_by(|a, b| {
        a.at.cmp(&b.at)
            .then_with(|| a.source.cmp(&b.source))
            .then_with(|| a.seq.cmp(&b.seq))
    });
    if query.limit > 0 && entries.len() as i64 > query.limit {
        entries = entries.split_off(entries.len() - query.limit as usize);
    }
    Ok(entries
        .into_iter()
        .map(|entry| ActivityJson {
            at: entry.at,
            kind: entry.kind,
            agent: entry.agent,
            summary: entry.summary,
            skill: entry.skill,
            skill_hash: entry.skill_hash,
        })
        .collect())
}

/// Internal row with ordering keys stripped from the API type.
#[derive(Debug, Clone)]
struct RankedActivity {
    at: String,
    kind: String,
    agent: Option<String>,
    summary: String,
    skill: Option<String>,
    skill_hash: Option<String>,
    seq: i64,
    source: Source,
}

/// Where an entry came from; declaration order is the tie-break order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Source {
    Message,
    Event,
}

/// A parsed `--since` bound.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Since {
    /// Ready-to-compare `YYYY-MM-DD HH:MM:SS` string.
    Absolute(String),
    /// SQLite modifier for `datetime('now', ?)` (e.g. `-2 hours`).
    Relative(String),
}

/// Parse `--since` into a comparison bound. Only the documented forms are
/// accepted (`aux activity` semantics); everything else is rejected.
fn parse_since(raw: &str) -> Result<Since, ActivityReadError> {
    let input = raw.trim();
    if let Some(modifier) = parse_relative(input) {
        return Ok(Since::Relative(modifier));
    }
    if let Some(absolute) = parse_absolute(input) {
        return Ok(Since::Absolute(absolute));
    }
    Err(ActivityReadError::Since {
        input: input.to_string(),
    })
}

/// Relative spans: `<count><s|m|h|d>`, e.g. `45s`, `30m`, `2h`, `7d`.
fn parse_relative(input: &str) -> Option<String> {
    let unit = input.chars().last()?;
    let digits = &input[..input.len() - unit.len_utf8()];
    let word = match unit {
        's' => "seconds",
        'm' => "minutes",
        'h' => "hours",
        'd' => "days",
        _ => return None,
    };
    if digits.is_empty() || !digits.bytes().all(|byte| byte.is_ascii_digit()) {
        return None;
    }
    let count: u64 = digits.parse().ok()?;
    // Bound the span so SQLite's date math can never overflow to NULL.
    if count == 0 || count > 1_000_000 {
        return None;
    }
    Some(format!("-{count} {word}"))
}

/// Absolute timestamps: `YYYY-MM-DD` or `YYYY-MM-DD HH:MM:SS`, with `T` and a
/// trailing `Z` tolerated. Output is normalized to the store's format.
fn parse_absolute(input: &str) -> Option<String> {
    let input = input.strip_suffix('Z').unwrap_or(input);
    let input = input.replace('T', " ");
    match input.len() {
        10 if valid_date(&input) => Some(format!("{input} 00:00:00")),
        19 if valid_datetime(&input) => Some(input),
        _ => None,
    }
}

fn valid_date(input: &str) -> bool {
    let bytes = input.as_bytes();
    if bytes.len() != 10
        || bytes[4] != b'-'
        || bytes[7] != b'-'
        || !digit_at(bytes, 0)
        || !digit_at(bytes, 1)
        || !digit_at(bytes, 2)
        || !digit_at(bytes, 3)
        || !digit_at(bytes, 5)
        || !digit_at(bytes, 6)
        || !digit_at(bytes, 8)
        || !digit_at(bytes, 9)
    {
        return false;
    }
    let year = number(input, 0, 4);
    let month = number(input, 5, 7);
    let day = number(input, 8, 10);
    (1970..=9999).contains(&year)
        && (1..=12).contains(&month)
        && (1..=days_in_month(year, month)).contains(&day)
}

/// Days in a month, Gregorian leap years included.
fn days_in_month(year: u32, month: u32) -> u32 {
    match month {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        2 if year.is_multiple_of(4) && (!year.is_multiple_of(100) || year.is_multiple_of(400)) => {
            29
        }
        2 => 28,
        _ => 0,
    }
}

fn valid_datetime(input: &str) -> bool {
    let bytes = input.as_bytes();
    bytes.len() == 19
        && bytes[10] == b' '
        && bytes[13] == b':'
        && bytes[16] == b':'
        && valid_date(&input[..10])
        && digit_at(bytes, 11)
        && digit_at(bytes, 12)
        && digit_at(bytes, 14)
        && digit_at(bytes, 15)
        && digit_at(bytes, 17)
        && digit_at(bytes, 18)
        && number(input, 11, 13) <= 23
        && number(input, 14, 16) <= 59
        && number(input, 17, 19) <= 59
}

fn digit_at(bytes: &[u8], position: usize) -> bool {
    bytes.get(position).is_some_and(u8::is_ascii_digit)
}

/// Parse a zero-padded number from `input[start..end]` (ASCII digits only).
fn number(input: &str, start: usize, end: usize) -> u32 {
    input[start..end].parse().unwrap_or(0)
}

fn read_events(
    home: &Path,
    conn: &Connection,
    agent: Option<&str>,
    since: Option<&Since>,
    limit: i64,
) -> Result<Vec<RankedActivity>, ActivityReadError> {
    if !table_exists(conn, "events").map_err(anyhow::Error::from)? {
        return Ok(Vec::new());
    }

    let mut sql = String::from("SELECT id, kind, payload, created_at FROM events WHERE 1 = 1");
    let mut params: Vec<Box<dyn rusqlite::ToSql>> = Vec::new();
    if let Some(agent) = agent {
        // `CASE` guarantees `json_extract` only sees valid JSON, so one junk
        // payload can never fail the whole query.
        sql.push_str(
            " AND (CASE WHEN json_valid(payload) THEN json_extract(payload, '$.agent') END) = ?",
        );
        params.push(Box::new(agent.to_string()));
    }
    append_since(&mut sql, "created_at", since, &mut params);
    sql.push_str(" ORDER BY created_at DESC, id DESC");
    sql.push_str(" LIMIT ?");
    params.push(Box::new(limit));

    let mut stmt = conn.prepare(&sql).map_err(anyhow::Error::from)?;
    let refs: Vec<&dyn rusqlite::ToSql> = params.iter().map(|param| param.as_ref()).collect();
    let rows = stmt
        .query_map(refs.as_slice(), |row| {
            Ok((
                row.get::<_, i64>(0)?,
                row.get::<_, String>(1)?,
                row.get::<_, String>(2)?,
                row.get::<_, String>(3)?,
            ))
        })
        .map_err(anyhow::Error::from)?;

    let mut entries = Vec::new();
    for row in rows {
        let (id, kind, payload, at) = row.map_err(anyhow::Error::from)?;
        entries.push(RankedActivity {
            at: clean_field(&at),
            kind: kind_display(home, &kind),
            agent: payload_agent(home, &payload),
            summary: event_summary(home, &kind, &payload),
            skill: payload_skill(home, &payload, "skill_name"),
            skill_hash: payload_skill_hash(&payload),
            seq: id,
            source: Source::Event,
        });
    }
    Ok(entries)
}

fn read_messages(
    home: &Path,
    conn: &Connection,
    agent: Option<&str>,
    since: Option<&Since>,
    limit: i64,
) -> Result<Vec<RankedActivity>, ActivityReadError> {
    if !table_exists(conn, "sessions").map_err(anyhow::Error::from)?
        || !table_exists(conn, "messages").map_err(anyhow::Error::from)?
    {
        return Ok(Vec::new());
    }

    // A private channel turn's rows live only while it runs (G1): they are
    // never an activity entry, so no `agent.state` can carry them. A chat
    // that ran in Private mode is left out entirely (CONV-PRIVATE-MIX): its
    // rows are the gated copy the provider saw, and they are never
    // rehydrated here.
    let open = aux_store::not_ever_private_session(conn, "s").map_err(anyhow::Error::from)?;
    let mut sql = format!(
        "SELECT m.id, s.agent, m.role, m.content, m.created_at, m.session_id
         FROM messages m JOIN sessions s ON s.id = m.session_id
         WHERE {} AND {open}",
        not_private_session("s")
    );
    let mut params: Vec<Box<dyn rusqlite::ToSql>> = Vec::new();
    if let Some(agent) = agent {
        sql.push_str(" AND s.agent = ?");
        params.push(Box::new(agent.to_string()));
    }
    append_since(&mut sql, "m.created_at", since, &mut params);
    sql.push_str(" ORDER BY m.created_at DESC, m.id DESC");
    sql.push_str(" LIMIT ?");
    params.push(Box::new(limit));

    let mut stmt = conn.prepare(&sql).map_err(anyhow::Error::from)?;
    let refs: Vec<&dyn rusqlite::ToSql> = params.iter().map(|param| param.as_ref()).collect();
    let rows = stmt
        .query_map(refs.as_slice(), |row| {
            Ok((
                row.get::<_, i64>(0)?,
                row.get::<_, String>(1)?,
                row.get::<_, String>(2)?,
                row.get::<_, String>(3)?,
                row.get::<_, String>(4)?,
                row.get::<_, i64>(5)?,
            ))
        })
        .map_err(anyhow::Error::from)?;

    let mut entries = Vec::new();
    for row in rows {
        let (id, agent, role, content, at, session_id) = row.map_err(anyhow::Error::from)?;
        // A private row holds tokens (PRIVATE-TRANSCRIPT): show its values,
        // resolved before the preview cap so a token is never cut in half.
        let content = if content.contains(kernel_privacy::PLACEHOLDER_OPEN) {
            super::display::rehydrate_text(home, session_id, &content)
        } else {
            content
        };
        let role = scrub_field(home, &role);
        let role = if role.is_empty() {
            "unknown".to_string()
        } else {
            role
        };
        let agent = scrub_field(home, &agent);
        entries.push(RankedActivity {
            at: clean_field(&at),
            kind: format!("message.{role}"),
            agent: (!agent.is_empty()).then_some(agent),
            summary: preview(home, &content),
            skill: None,
            skill_hash: None,
            seq: id,
            source: Source::Message,
        });
    }
    Ok(entries)
}

/// Append the `since` predicate for a timestamp column.
fn append_since(
    sql: &mut String,
    column: &str,
    since: Option<&Since>,
    params: &mut Vec<Box<dyn rusqlite::ToSql>>,
) {
    match since {
        None => {}
        Some(Since::Absolute(value)) => {
            sql.push_str(&format!(" AND {column} >= ?"));
            params.push(Box::new(value.clone()));
        }
        Some(Since::Relative(modifier)) => {
            sql.push_str(&format!(" AND {column} >= datetime('now', ?)"));
            params.push(Box::new(modifier.clone()));
        }
    }
}

/// Display kind: sanitized, scrubbed, single-line, capped like any other field.
fn kind_display(home: &Path, kind: &str) -> String {
    let cleaned = scrub_field(home, kind);
    if cleaned.is_empty() {
        "unknown".to_string()
    } else {
        truncate_chars(&cleaned, ACTIVITY_SUMMARY_MAX_CHARS)
    }
}

/// Agent named in an event payload, when present and well-formed.
fn payload_agent(home: &Path, payload: &str) -> Option<String> {
    let value: serde_json::Value = serde_json::from_str(payload).ok()?;
    let agent = scrub_field(home, value.get("agent")?.as_str()?);
    (!agent.is_empty()).then_some(agent)
}

/// Skill name in an event payload (`skill.*` events), scrubbed like any field.
fn payload_skill(home: &Path, payload: &str, key: &str) -> Option<String> {
    let value: serde_json::Value = serde_json::from_str(payload).ok()?;
    let name = scrub_field(home, value.get(key)?.as_str()?);
    (!name.is_empty()).then(|| truncate_chars(&name, 80))
}

/// Skill hash in an event payload. Only a plain digest passes: ASCII letters,
/// digits, `:` `-` `_`, at most 128 characters; anything else is dropped.
fn payload_skill_hash(payload: &str) -> Option<String> {
    let value: serde_json::Value = serde_json::from_str(payload).ok()?;
    let hash = value.get("skill_hash")?.as_str()?.trim();
    let plain = !hash.is_empty()
        && hash.len() <= 128
        && hash
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, ':' | '-' | '_'));
    plain.then(|| hash.to_string())
}

/// One-line digest of an event (same rules as `aux activity`).
pub fn event_summary(home: &Path, kind: &str, payload: &str) -> String {
    let Ok(mut value) = serde_json::from_str::<serde_json::Value>(payload) else {
        return preview(home, payload);
    };
    // B3-02: scrub the value tree *before* any re-serialisation, so an escape
    // `serde_json` introduces can never hide a credential key from the walk.
    kernel_broker::scrub_json_value(&mut value);
    match kind.trim() {
        "tool.decision" => {
            let tool = value.get("tool").and_then(|v| v.as_str()).unwrap_or("tool");
            let outcome = value
                .get("outcome")
                .and_then(|v| v.as_str())
                .unwrap_or("unknown");
            match value.get("reason").and_then(|v| v.as_str()) {
                Some(reason) if !reason.trim().is_empty() => {
                    preview(home, &format!("{tool} {outcome} — {reason}"))
                }
                _ => preview(home, &format!("{tool} {outcome}")),
            }
        }
        "daemon.started" => match value.get("version").and_then(|v| v.as_str()) {
            Some(version) if !version.trim().is_empty() => {
                // P1-2: scrub the version *before* gluing the `v` marker —
                // scrubbing after the glue hides every prefixed shape behind
                // a non-boundary leading character.
                let cleaned = scrub_field(home, version);
                truncate_chars(&format!("v{cleaned}"), ACTIVITY_SUMMARY_MAX_CHARS)
            }
            _ => preview(home, &compact_json(&value)),
        },
        _ => {
            for key in ["summary", "reason", "message"] {
                if let Some(text) = value.get(key).and_then(|v| v.as_str()) {
                    if !text.trim().is_empty() {
                        return preview(home, text);
                    }
                }
            }
            preview(home, &compact_json(&value))
        }
    }
}

fn compact_json(value: &serde_json::Value) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| value.to_string())
}

/// One-line summary: full detector first, then sanitized, secret-scrubbed,
/// collapsed and capped. Detection must precede the collapse: a value on the
/// second line is whole in the raw text, not after lines are joined.
fn preview(home: &Path, raw: &str) -> String {
    preview_capped(home, raw, ACTIVITY_SUMMARY_MAX_CHARS)
}

fn preview_capped(home: &Path, raw: &str, max: usize) -> String {
    // Secret shapes first, without collapsing lines: their established marker
    // stays `<redacted>`, then the full detector labels the PII shapes.
    let redacted = super::error::scrub_preview(home, raw, FIELD_SCRUB_BYTES);
    let detected = kernel_broker::scrub_display_text(&redacted, FIELD_SCRUB_BYTES);
    let cleaned = scrub_field(home, &detected);
    if cleaned.is_empty() {
        return "(empty)".to_string();
    }
    truncate_chars(&cleaned, max)
}

