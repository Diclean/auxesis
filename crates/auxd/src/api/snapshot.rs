/// Summary cap of one activity line, matching `aux activity`.
pub const ACTIVITY_SUMMARY_MAX_CHARS: usize = 200;

/// Byte budget for scrubbing one short display field (role, agent, kind):
/// [scrub_field] then collapses to one line, so this is generous.
const FIELD_SCRUB_BYTES: usize = 4096;

/// Sanitize, scrub and collapse one store-provided display field.
///
/// F-03 (audit C P2-1): the activity digest and the WS frames used to go
/// through `clean_field` alone, so a `ghp_…`/PEM/`Bearer` secret in a stored
/// message or event payload was re-exposed on those surfaces even though the
/// messages view scrubs it. Every field on this path now runs the one shared
/// [`super::error::scrub_preview`], exactly like
/// [`message_json_scrubbed`].
pub fn scrub_field(home: &Path, raw: &str) -> String {
    clean_field(&super::error::scrub_preview(home, raw, FIELD_SCRUB_BYTES))
}

