/// The store sessions, newest activity first.
///
/// `hide_private` leaves out the chats that ran in Private mode
/// (CONV-PRIVATE-MIX): their titles are the owner's private business, so
/// they are listed nowhere. The agent *names* still come from every session:
/// which agents exist is not private.
fn read_sessions(conn: &Connection, hide_private: bool) -> anyhow::Result<Vec<Session>> {
    if !table_exists(conn, "sessions")? {
        return Ok(Vec::new());
    }
    let mut filter = not_private_session("s");
    if hide_private {
        filter = format!(
            "{filter} AND {}",
            aux_store::not_ever_private_session(conn, "s")?
        );
    }
    let mut stmt = conn.prepare(&format!(
        "SELECT id, agent, title, created_at, updated_at
         FROM sessions s WHERE {filter} ORDER BY updated_at DESC, id DESC",
    ))?;
    let rows = stmt.query_map([], row_to_session)?;
    Ok(rows.collect::<Result<Vec<_>, _>>()?)
}

pub const CONVERSATIONS_LIMIT: i64 = 50;
const CONVERSATION_TITLE_CHARS: usize = 60;

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct ConversationJson {
    pub id: i64,
    pub title: String,
    pub updated_at: String,
}

/// Read Aux's `chat` sessions with a message. A job, private or other agent's
/// thread is never one of the owner's Aux chats.
pub fn read_conversations(home: &Path) -> anyhow::Result<Vec<ConversationJson>> {
    let Some(conn) = open_read_only(home)? else {
        return Ok(Vec::new());
    };
    if !table_exists(&conn, "sessions")? || !table_exists(&conn, "messages")? {
        return Ok(Vec::new());
    }
    let filter = chat_session_filter(&conn, "s")?;
    let not_private = not_private_session_filter(&conn)?;
    // A chat that ever ran a Private turn is never one of the owner's Aux
    // chats (CONV-PRIVATE-MIX), and a chat with no system row never was one
    // either: both conditions must pass.
    let mut stmt = conn.prepare(&format!(
        "SELECT s.id, COALESCE(NULLIF(TRIM(s.title), ''),
           (SELECT m.content FROM messages m
             WHERE m.session_id = s.id AND m.role = 'user'
             ORDER BY m.id ASC LIMIT 1)) AS title,
           s.updated_at
         FROM sessions s
         WHERE s.agent = 'aux' AND {filter}
           AND {not_private}
           AND EXISTS (SELECT 1 FROM messages m
                        WHERE m.session_id = s.id AND m.role = 'system')
         ORDER BY s.updated_at DESC, s.id DESC LIMIT ?1"
    ))?;
    let read = |row: &rusqlite::Row| -> rusqlite::Result<(i64, Option<String>, String)> {
        Ok((row.get(0)?, row.get(1)?, row.get(2)?))
    };
    let rows = stmt.query_map([CONVERSATIONS_LIMIT], read)?;
    rows.map(|row| -> anyhow::Result<ConversationJson> {
        let (id, title, updated_at) = row?;
        let title = conversation_title(home, title.as_deref().unwrap_or(""));
        Ok(ConversationJson {
            id,
            title,
            updated_at,
        })
    })
    .collect()
}

/// SQL predicate: the session aliased `alias` may be read back
/// (CONV-PRIVATE-MIX): it never ran in Private mode, **or** it is the
/// agent's current session — the one the store treats as the active chat,
/// the one new turns go to.
///
/// The Mac app reloads the open chat with `GET /v1/threads/{agent}/messages`
/// on launch and on a reconnect, so a live Private chat must survive that
/// reload. Every other surface (the conversations list, the agents' threads,
/// the activity, `unread`, select, the numeric-id read) keeps the plain
/// filter: the exemption is for the transcript read of the current session
/// only.
fn current_session_or_not_ever_private(conn: &Connection, alias: &str) -> anyhow::Result<String> {
    let flag = aux_store::not_ever_private_session(conn, alias)?;
    let current = current_session_id_sql(conn, alias)?;
    Ok(format!("({flag} OR {alias}.id = {current})"))
}

/// SQL predicate: the session aliased `s` never ran a Private turn
/// (CONV-PRIVATE-MIX). It passes only when **both** rules hold:
///
/// - the sticky `ever_private` mark is clear (the shared helper
///   [`aux_store::not_ever_private_session`], used by every read path);
/// - no stored row carries a token marker. A Private turn stores the *gated*
///   copy the provider saw, whose tokens the kernel writes as
///   `⟦KIND_0123456789AB⟧`; an Open turn stores the plain text, so a marker
///   proves a Private turn ran there. The shape is the kernel's own
///   (`kernel-privacy`'s `session_token_len`), so a literal `⟦` in an Open
///   message is not a marker and the chat stays Open.
fn not_private_session_filter(conn: &Connection) -> anyhow::Result<String> {
    let flag = aux_store::not_ever_private_session(conn, "s")?;
    let globs = token_marker_globs();
    let tests = globs
        .iter()
        .map(|glob| format!("m.content GLOB '{glob}'"))
        .collect::<Vec<_>>()
        .join(" OR ");
    Ok(format!(
        "{flag} AND NOT EXISTS (SELECT 1 FROM messages m
             WHERE m.session_id = s.id AND ({tests}))"
    ))
}

/// The GLOB patterns of the kernel's token shape: `⟦`, an uppercase kind,
/// `_`, 12 uppercase hex digits, an optional `_<digits>`, then `⟧`.
///
/// The kernel mints `KIND_<12 hex>` and, when two values share that prefix,
/// `KIND_<12 hex>_<n>` for `n` counting up (`anonymize`'s `make_token`), so
/// the suffix is a digit run of any length — `_1` to `_9` and longer. SQLite's
/// GLOB cannot repeat a character class, so the run is matched in three
/// shapes: no suffix, one digit, and two or more (the tail of a long run is
/// matched loosely, so a suffix with a letter in it is read as a marker:
/// over-excluding is the safe direction).
fn token_marker_globs() -> Vec<String> {
    let hex = "[0-9A-F]".repeat(12);
    vec![
        format!("*⟦[A-Z_]*_{hex}⟧*"),
        format!("*⟦[A-Z_]*_{hex}_[0-9]⟧*"),
        format!("*⟦[A-Z_]*_{hex}_[0-9][0-9]*⟧*"),
    ]
}

fn conversation_title(home: &Path, raw: &str) -> String {
    let first = raw
        .split('\n')
        .map(str::trim)
        .find(|l| !l.is_empty())
        .unwrap_or("");
    // A stored title may predate title scrubbing, or be the first message
    // itself; the full kernel detector labels any e-mail, IBAN or card.
    truncate_chars(
        &scrub_field(home, &kernel_broker::scrub_title(first)),
        CONVERSATION_TITLE_CHARS,
    )
}

/// Newest session **with at least one message** per agent: the agent's current
/// thread. A bare session (created outside the engine, never used) does not
/// count, so a fresh send never appends to an empty shell, and job sessions
/// (BAPIV2-08) never become the chat thread.
fn read_current_sessions(conn: &Connection) -> anyhow::Result<HashMap<String, Session>> {
    if !table_exists(conn, "sessions")? || !table_exists(conn, "messages")? {
        return Ok(HashMap::new());
    }
    let filter = chat_session_filter(conn, "s")?;
    let (used, order) = current_session_sql(conn, "s")?;
    // A chat that ran in Private mode does not drive the agents snapshot's
    // thread or its unread flag (CONV-PRIVATE-MIX).
    let open = aux_store::not_ever_private_session(conn, "s")?;
    let mut stmt = conn.prepare(&format!(
        "SELECT id, agent, title, created_at, updated_at
         FROM sessions s
         WHERE {filter}
           AND {open}
           AND {used}
         ORDER BY {order}",
    ))?;
    let rows = stmt.query_map([], row_to_session)?;
    let mut current: HashMap<String, Session> = HashMap::new();
    for session in rows {
        let session = session?;
        current.entry(session.agent.clone()).or_insert(session);
    }
    Ok(current)
}

/// SQL predicate selecting *chat* sessions: a job run's transcript must never
/// be an agent's current thread.
///
/// `kind` is authoritative for every session written since the durable column
/// became mandatory. The `job <name>` title heuristic is kept **only for
/// legacy rows**: sessions whose id is at or below the v8 watermark
/// (`meta.sessions_kind_legacy_max_id`), which predate the column or were
/// backfilled by title at v7. A genuine post-v8 chat is never hidden by a
/// title collision (RV2-05).
fn chat_session_filter(conn: &Connection, alias: &str) -> anyhow::Result<String> {
    let mut filter = format!("{alias}.kind = 'chat'");
    if table_exists(conn, "jobs")? {
        let watermark = legacy_session_max_id(conn)?;
        filter.push_str(&format!(
            " AND ({alias}.id > {watermark} OR NOT EXISTS (
                 SELECT 1 FROM jobs j
                 WHERE j.agent = {alias}.agent AND {alias}.title = 'job ' || j.name
             ))"
        ));
    }
    Ok(filter)
}

/// SQL predicate and order for the current thread: a session with a message, or the one
/// `/new` started, ranked first so a late turn on the old one never wins (NEW-CHAT-1).
fn current_session_sql(conn: &Connection, alias: &str) -> anyhow::Result<(String, String)> {
    let used = format!("EXISTS (SELECT 1 FROM messages m WHERE m.session_id = {alias}.id)");
    let order = format!("{alias}.updated_at DESC, {alias}.id DESC");
    if !table_exists(conn, "meta")? {
        return Ok((used, order));
    }
    let marked = format!(
        "{alias}.id = (SELECT CAST(value AS INTEGER) FROM meta WHERE key = '{}' || {alias}.agent)",
        aux_store::META_CHAT_NEW_PREFIX
    );
    let ranked = format!("({marked}) DESC, {order}");
    Ok((format!("({used} OR {marked})"), ranked))
}

/// SQL expression: the id of the session the store treats as the agent's
/// active chat — the one new turns go to (CONV-PRIVATE-MIX).
///
/// It is the same shape as [`aux_store::Store::current_chat_session`]: the
/// newest chat session with a message, or the one `/new` marked, job
/// transcripts left out. `NULL` when the store is too old to keep the mark.
fn current_session_id_sql(conn: &Connection, alias: &str) -> anyhow::Result<String> {
    if !table_exists(conn, "meta")? {
        return Ok("NULL".to_string());
    }
    let filter = chat_session_filter(conn, "c")?;
    let (used, order) = current_session_sql(conn, "c")?;
    Ok(format!(
        "(SELECT c.id FROM sessions c
          WHERE c.agent = {alias}.agent AND {filter} AND {used}
          ORDER BY {order} LIMIT 1)"
    ))
}

/// Highest session id that existed when the durable `kind` column became the
/// authority (v8 watermark). `0` when the key is absent or the store predates
/// v8: by definition no id is ≤ 0, so no session is treated as legacy.
fn legacy_session_max_id(conn: &Connection) -> anyhow::Result<i64> {
    if !table_exists(conn, "meta")? {
        return Ok(0);
    }
    let raw: Option<String> = conn
        .query_row(
            "SELECT value FROM meta WHERE key = ?1",
            [aux_store::META_SESSION_LEGACY_MAX_ID],
            |row| row.get(0),
        )
        .optional()?;
    Ok(raw.and_then(|value| value.parse().ok()).unwrap_or(0))
}

