//! Read-only snapshots of the store for the local API.
//!
//! Every reader mirrors an existing `aux` command instead of inventing a new
//! semantic:
//!
//! - [`read_activity`] ports `aux activity`'s merge (messages ∪ events,
//!   ascending, same-second ties messages-first) and its summary rules;
//! - [`usage_snapshot`] ports `aux usage`'s day-bounded totals and per-agent
//!   caps (`config.budgets.caps_for`);
//! - [`agents_snapshot`] ports the desktop app's agent union (config, jobs,
//!   sessions, usage, agent directories) plus live state (running job, STOP,
//!   today's usage, last activity);
//! - [`thread_messages`] pages `messages` by descending id, then reverses the
//!   window so pages stay in conversation order.
//!
//! **Reads never write.** All connections here are opened
//! `SQLITE_OPEN_READ_ONLY` (no migration, no `Store::open` side effects), and
//! a missing store or missing table simply yields an empty answer — the same
//! discipline as `aux activity`. This keeps the 1 Hz WS poller from touching
//! the disk on an idle daemon. The API's writing paths are the chat turn
//! ([`super::turn`]) and the agent writes ([`super::agents`], B-API v3); this
//! module only reads (the agent sidecar/soul reads it exposes never create a
//! file).
//!
//! Every string leaving this module is sanitized (control/invisible
//! characters stripped), secret-scrubbed through the shared
//! [`super::error::scrub_preview`] and capped.

