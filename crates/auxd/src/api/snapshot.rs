        let after_session = change_stamp(&home);
        assert_ne!(before, after_session, "new session");

        store
            .append_message(session.id, "user", "hi", None)
            .unwrap();
        let after_message = change_stamp(&home);
        assert_ne!(after_session, after_message, "new message");

