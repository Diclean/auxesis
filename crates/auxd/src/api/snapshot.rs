/// A day-shaped usage snapshot (`/v1/usage`).
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct UsageTotalsJson {
    /// Tokens sent to the provider.
    pub tokens_in: u64,
    /// Tokens generated by the provider.
    pub tokens_out: u64,
    /// Money spent, in cents.
    pub usd_cents: u64,
}

impl From<UsageTotals> for UsageTotalsJson {
    fn from(totals: UsageTotals) -> Self {
        Self {
            tokens_in: totals.tokens_in,
            tokens_out: totals.tokens_out,
            usd_cents: totals.usd_cents,
        }
    }
}

/// Effective daily caps of one agent (`null` = uncapped).
