/// Resolve a `threads/:id` segment: a pure-digit segment is a session id
/// (`None` = not found), anything else an agent name.
pub fn resolve_thread(home: &Path, id: &str) -> Result<Option<ThreadTarget>, ThreadError> {
    if !id.is_empty() && id.bytes().all(|byte| byte.is_ascii_digit()) {
        let session_id: i64 = match id.parse() {
            Ok(session_id) => session_id,
            Err(_) => return Ok(None), // absurdly long digit run
        };
        if session_id <= 0 {
            return Ok(None);
        }
        return match read_session(home, session_id)? {
            Some(session) => Ok(Some(ThreadTarget::Session(session_json(home, &session)))),
            None => Ok(None),
        };
    }

    aux_engine::validate_agent(id).map_err(|err| ThreadError::InvalidAgent {
        agent: id.to_string(),
        reason: err.to_string(),
    })?;
    let latest = latest_session_for_agent(home, id)?;
    Ok(Some(ThreadTarget::Agent {
        name: id.to_string(),
        latest: latest.map(|session| session_json(home, &session)),
    }))
}

/// Read one page of messages for a resolved thread. `before` is exclusive.
pub fn thread_messages(
    home: &Path,
    target: &ThreadTarget,
    before: Option<i64>,
    limit: i64,
) -> anyhow::Result<MessagesPageJson> {
    let thread = match target {
        ThreadTarget::Session(session) => Some(session.clone()),
        ThreadTarget::Agent { latest, .. } => latest.clone(),
    };
    let Some(session) = &thread else {
        return Ok(MessagesPageJson {
            thread: None,
            messages: Vec::new(),
            has_more: false,
            oldest_id: None,
        });
    };
    let (messages, has_more) = read_message_page(home, session.id, before, limit)?;
    let oldest_id = messages.first().map(|message| message.id);
    Ok(MessagesPageJson {
        thread,
        messages,
        has_more,
        oldest_id,
    })
}

/// Newest `limit` messages with `id < before` (all when `before` is `None`),
/// returned in ascending conversation order.
fn read_message_page(
    home: &Path,
    session_id: i64,
    before: Option<i64>,
    limit: i64,
) -> anyhow::Result<(Vec<MessageJson>, bool)> {
    let Some(conn) = open_read_only(home)? else {
        return Ok((Vec::new(), false));
    };
    if !table_exists(&conn, "messages")? {
        return Ok((Vec::new(), false));
    }
    let mut stmt = conn.prepare(
        "SELECT id, session_id, role, content, created_at, meta
         FROM messages
         WHERE session_id = ?1 AND (?2 IS NULL OR id < ?2)
         ORDER BY id DESC
         LIMIT ?3",
    )?;
    let rows = stmt.query_map(rusqlite::params![session_id, before, limit + 1], |row| {
        Ok(Message {
            id: row.get(0)?,
            session_id: row.get(1)?,
            role: row.get(2)?,
            content: row.get(3)?,
            created_at: row.get(4)?,
            // DELEGATION-SOURCE-1: the row's metadata names its source.
            meta: row.get(5)?,
        })
    })?;
    let mut messages = rows.collect::<Result<Vec<_>, _>>()?;
    let has_more = messages.len() as i64 > limit;
    if has_more {
        messages.truncate(limit as usize);
    }
    messages.reverse();
    Ok((
        messages
            .iter()
            .map(|message| message_json_scrubbed(home, message))
            .collect(),
        has_more,
    ))
}

fn read_session(home: &Path, id: i64) -> anyhow::Result<Option<Session>> {
    let Some(conn) = open_read_only(home)? else {
        return Ok(None);
    };
    if !table_exists(&conn, "sessions")? {
        return Ok(None);
    }
    // A private channel turn's session is never a thread the app can read,
    // and a chat that ran in Private mode is never read back (CONV-PRIVATE-MIX).
    let open = aux_store::not_ever_private_session(&conn, "s")?;
    let session = conn
        .query_row(
            &format!(
                "SELECT id, agent, title, created_at, updated_at FROM sessions s
                 WHERE id = ?1 AND {} AND {open}",
                not_private_session("s")
            ),
            [id],
            row_to_session,
        )
        .map(Some)
        .or_else(|err| match err {
            rusqlite::Error::QueryReturnedNoRows => Ok(None),
            other => Err(other),
        })?;
    Ok(session)
}

/// SQL predicate: the session aliased `alias` is not a private channel
/// turn's. Its rows exist on disk only while the turn runs, then are deleted.
pub(crate) fn not_private_session(alias: &str) -> String {
    format!(
        "{alias}.kind <> '{}'",
        crate::gateway::imessage::PRIVATE_SESSION_KIND
    )
}

/// The agent's current session: the latest **chat** session with messages
/// (the one new turns go to). Job sessions are excluded (see
/// [`chat_session_filter`]).
///
/// CONV-PRIVATE-MIX: the current session is exempt from the Private filter —
/// it is the chat the app reloads on launch and on a reconnect, so a live
/// Private chat must survive that reload. Every other marked chat is still
/// left out everywhere.
pub(crate) fn latest_session_for_agent(
    home: &Path,
    agent: &str,
) -> anyhow::Result<Option<Session>> {
    let Some(conn) = open_read_only(home)? else {
        return Ok(None);
    };
    if !table_exists(&conn, "sessions")? || !table_exists(&conn, "messages")? {
        return Ok(None);
    }
    let filter = chat_session_filter(&conn, "s")?;
    let (used, order) = current_session_sql(&conn, "s")?;
    let open = current_session_or_not_ever_private(&conn, "s")?;
    let session = conn
        .query_row(
            &format!(
                "SELECT id, agent, title, created_at, updated_at
                 FROM sessions s
                 WHERE s.agent = ?1
                   AND {filter}
                   AND {open}
                   AND {used}
                 ORDER BY {order}
                 LIMIT 1",
            ),
            [agent],
            row_to_session,
        )
        .map(Some)
        .or_else(|err| match err {
            rusqlite::Error::QueryReturnedNoRows => Ok(None),
            other => Err(other),
        })?;
    Ok(session)
}

/// The stored token table of `session_id` (PRIVATE-TRANSCRIPT), empty when the
/// store or the table is not there. Values are the owner's: never log them.
pub(crate) fn session_token_pairs(
    home: &Path,
    session_id: i64,
) -> anyhow::Result<Vec<(String, String)>> {
    let Some(conn) = open_read_only(home)? else {
        return Ok(Vec::new());
    };
    if !table_exists(&conn, "session_tokens")? {
        return Ok(Vec::new());
    }
    let mut statement =
        conn.prepare("SELECT token, value FROM session_tokens WHERE session_id = ?1")?;
    let pairs = statement
        .query_map([session_id], |row| Ok((row.get(0)?, row.get(1)?)))?
        .collect::<rusqlite::Result<Vec<(String, String)>>>()?;
    Ok(pairs)
}

fn row_to_session(row: &rusqlite::Row<'_>) -> rusqlite::Result<Session> {
    Ok(Session {
        id: row.get(0)?,
        agent: row.get(1)?,
        title: row.get(2)?,
        created_at: row.get(3)?,
        updated_at: row.get(4)?,
    })
}

/// Session → JSON, sanitized and secret-scrubbed (the title is derived from
/// user text, so it is one of the surfaces F-03 covers). The title also runs
/// the full detector, so an agent's thread list cannot show an e-mail, phone,
/// IBAN, card or national ID from a legacy row.
pub fn session_json(home: &Path, session: &Session) -> SessionJson {
    SessionJson {
        id: session.id,
        agent: clean_field(&session.agent),
        title: session.title.as_deref().map(|title| {
            preview_capped(
                home,
                &kernel_broker::scrub_title(title),
                ACTIVITY_SUMMARY_MAX_CHARS,
            )
        }),
        created_at: clean_field(&session.created_at),
        updated_at: clean_field(&session.updated_at),
    }
}

/// Message → JSON, sanitized and capped.
pub fn message_json(message: &Message) -> MessageJson {
    MessageJson {
        id: message.id,
        thread_id: message.session_id,
        role: {
            let role = clean_field(&message.role);
            if role.is_empty() {
                "unknown".to_string()
            } else {
                role
            }
        },
        content: sanitize_external_text(&message.content, MESSAGE_MAX_BYTES),
        preview: String::new(),
        at: clean_field(&message.created_at),
        source: message_source(message),
    }
}

/// DELEGATION-SOURCE-1: the row's source, read from its metadata
/// (`{"source": "delegation"}`). A row stored before the field existed, or
/// one whose metadata names no source, reads as the owner's own words.
fn message_source(message: &Message) -> Option<String> {
    let meta = message.meta.as_deref()?;
    let value: serde_json::Value = serde_json::from_str(meta).ok()?;
    let source = value.get("source")?.as_str()?;
    let source = clean_field(source);
    (!source.is_empty()).then_some(source)
}

/// Message → JSON for a client response (REST page, POST result, live frame):
/// the same shape as [`message_json`], except that **content is scrubbed on
/// every role** — home path → `<home>`, every documented secret shape
/// redacted (RV2-02, P2-5).
///
/// The persisted row stays raw: the model's resume history needs the real
/// value, and only the display framing is redacted. Scrubbing `assistant`
/// and `user` rows like `tool` rows keeps the live `message.new` (wire.rs),
/// a reloaded `GET /v1/threads/{id}/messages` and the `/v1/activity` digest
/// from disagreeing about the same stored text.
pub fn message_json_scrubbed(home: &Path, message: &Message) -> MessageJson {
    let mut json = message_json(message);
    json.content = super::error::scrub_preview(home, &json.content, MESSAGE_MAX_BYTES);
    json.preview = message_preview(home, &message.content);
    json
}

/// The daemon-built one-line sidebar preview: full detector first (so a value
/// on a later line is labelled), then collapse and cap. Swift renders this
/// field only; it derives no preview from raw text.
pub(crate) fn message_preview(home: &Path, raw: &str) -> String {
    let redacted = super::error::scrub_preview(home, raw, FIELD_SCRUB_BYTES);
    let detected = kernel_broker::scrub_display_text(&redacted, FIELD_SCRUB_BYTES);
    truncate_chars(&scrub_field(home, &detected), ACTIVITY_SUMMARY_MAX_CHARS)
}

