/// Open the store read-only, or `None` when it does not exist yet.
///
/// Never creates or migrates: the API is a read-only guest here.
fn open_read_only(home: &Path) -> anyhow::Result<Option<Connection>> {
    let path: PathBuf = store_path(home);
    if !path.exists() {
        return Ok(None);
    }
    let conn = aux_store::open_keyed_readonly(&path)?;
    // A daemon may be mid-write; wait instead of failing on a transient lock.
    let _ = conn.busy_timeout(Duration::from_secs(2));
    Ok(Some(conn))
}

fn table_exists(conn: &Connection, name: &str) -> rusqlite::Result<bool> {
    let count: i64 = conn.query_row(
        "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = ?1",
        [name],
        |row| row.get(0),
    )?;
    Ok(count > 0)
}

