public extension L10n {
    static func ui(_ key: UIKey, _ language: Language) -> String {
        if let value = uiTable[key]?[language], !value.isEmpty { return value }
        return uiTable[key]?[.en] ?? key.rawValue
    }

    static func uf(_ key: UIKey, _ language: Language, _ arguments: CVarArg...) -> String {
        String(format: ui(key, language), arguments: arguments)
    }

    /// EN source copy. FR slots are added here, per key, when French returns.
    static let uiTable: [UIKey: [Language: String]] = {
        var table: [UIKey: [Language: String]] = [:]
        for (key, english) in uiEnglish {
            table[key] = [.en: english]
        }
        for (key, french) in uiFrench {
            table[key]?[.fr] = french
        }
        return table
    }()

