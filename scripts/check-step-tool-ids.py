#!/usr/bin/env python3
"""Keep the app's step tool ids honest.

The daemon registers its tools in Rust; the app labels them in Swift. This
script reads the registration sites, writes the checked-in fixture, and fails
when the fixture no longer matches them.

    scripts/check-step-tool-ids.py --write   regenerate the fixture
    scripts/check-step-tool-ids.py --check   fail when it is stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "apps/auxesis-mac/Tests/AuxesisKitTests/Fixtures/step-tools.txt"
HEADER = """# Tool ids the daemon registers, for StepLabel's EN/FR words.
# Generated by scripts/check-step-tool-ids.py --write; do not edit by hand.
"""

# aux-engine/src/config.rs registers the builtins; their names live in
# aux-runtime/src/tools. The connectors and app tools live in auxd. Every file
# under these roots is scanned, so a new tool file is caught without editing
# this script.
ROOTS = [
    "crates/aux-runtime/src/tools",
    "crates/aux-mail/src",
    "crates/aux-google/src",
    "crates/auxd/src",
]
# A plain `Tool` (not `NativeTool`) names itself in `fn name`; watch is the one
# such tool today. Other `fn name`s in the tree are not tools.
PLAIN_TOOL_FILES = ["crates/auxd/src/watch.rs"]

NATIVE = re.compile(r"fn native_name\(&self\)[^{]*\{(.*?)\n    \}", re.S)
NAME = re.compile(r"fn name\(&self\)[^{]*\{(.*?)\n    \}", re.S)
LITERAL = re.compile(r'"([a-z][a-z0-9_]+)"')
CONST = re.compile(r'const ([A-Z][A-Z0-9_]*): &str = "([^"]+)";')
READ_TOOL = re.compile(r'read_tool!\([^,]+,[^,]+,\s*"([a-z0-9_]+)"', re.S)


def generated_ids():
    found = set()
    tool_map = (ROOT / "crates/aux-runtime/src/skills/tool_map.rs").read_text()
    static = tool_map.split("const STATIC_TOOLS", 1)[1].split("];", 1)[0]
    found.update(match[1] for match in re.findall(r'\(\s*"([^"]+)",\s*"([^"]+)"', static))
    sources = [
        path
        for root in ROOTS
        for path in sorted((ROOT / root).rglob("*.rs"))
    ]
    for path in sources:
        # Test-only tools are not registered by the daemon.
        source = re.split(r"#\[cfg\(test\)\]\s*mod tests\b", path.read_text(), maxsplit=1)[0]
        consts = dict(CONST.findall(source))
        for body in NATIVE.findall(source):
            found.update(LITERAL.findall(body))
            for const in re.findall(r"\b([A-Z][A-Z0-9_]+)\b", body):
                if const in consts:
                    found.add(consts[const])
        found.update(READ_TOOL.findall(source))
    for name in PLAIN_TOOL_FILES:
        for body in NAME.findall((ROOT / name).read_text()):
            found.update(LITERAL.findall(body))
    return sorted(found)


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("--write", "--check"):
        print("usage: check-step-tool-ids.py --write|--check", file=sys.stderr)
        return 2
    generated = generated_ids()
    if sys.argv[1] == "--write":
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(HEADER + "\n".join(generated) + "\n")
        print(f"step-tool-ids: wrote {len(generated)} tools")
        return 0
    if not FIXTURE.exists():
        print(f"step-tool-ids: missing {FIXTURE}", file=sys.stderr)
        return 1
    checked = [
        line.strip()
        for line in FIXTURE.read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    if checked == generated:
        print(f"step-tool-ids: OK ({len(generated)} tools)")
        return 0
    for tool in sorted(set(generated) - set(checked)):
        print(f"step-tool-ids: missing from the fixture: {tool}", file=sys.stderr)
    for tool in sorted(set(checked) - set(generated)):
        print(f"step-tool-ids: stale in the fixture: {tool}", file=sys.stderr)
    print("step-tool-ids: run scripts/check-step-tool-ids.py --write", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
