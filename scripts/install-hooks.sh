#!/usr/bin/env bash
# Install the versioned git hooks: point core.hooksPath at .githooks/.
# The pre-commit hook refuses secret-looking content and personal data
# (scripts/check-no-secrets.sh, which also runs
# scripts/check-personal-data.sh).
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

if [[ ! -d .githooks ]]; then
    echo "install-hooks: .githooks/ is missing — refusing to point core.hooksPath at nothing" >&2
    exit 1
fi

# pre-push is generated here (rewritten on every install), so it is not a
# versioned file. Emergencies only: git push --no-verify skips it.
cat > .githooks/pre-push <<'EOF'
#!/usr/bin/env bash
# Generated by scripts/install-hooks.sh: the fast gate before every push.
exec scripts/gate-fast.sh
EOF

chmod +x .githooks/pre-commit .githooks/pre-push
git config core.hooksPath .githooks

echo "installed: core.hooksPath -> .githooks (pre-commit: scripts/check-no-secrets.sh; pre-push: scripts/gate-fast.sh)"
