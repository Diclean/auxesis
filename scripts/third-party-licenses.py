#!/usr/bin/env python3
"""Write the third-party licence list of the locked dependency graph.

Usage: python3 -I scripts/third-party-licenses.py <destination-directory>

The list has the `cargo about list` shape — one line per crate, with its
version and its licence expression — built from `cargo metadata --format-version
1 --locked --offline`: no new dependency and no network. It names the
components of NOTICE first, then the crates that come from a registry. The
crates of this workspace are Auxesis itself, not third-party, so they are not
in this list: they are covered by the Apache-2.0 text of LICENSE, which the
app bundle carries next to this file. The app bundle carries its own copy
(scripts/package-mac.sh writes it into the bundle at package time), and a copy
is published at the repository root, so a reader can see the licences before
the first release. Refresh that copy with

    python3 -I scripts/third-party-licenses.py .

whenever Cargo.lock changes.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILENAME = "THIRD-PARTY-LICENSES.txt"
NOTICE = ROOT / "NOTICE"
# The one command that reads the graph: offline, so a package build never
# needs the network, and --locked, so the list matches Cargo.lock.
METADATA = ["cargo", "metadata", "--format-version", "1", "--locked", "--offline"]

HEADER = """\
# Third-party licences
#
# Generated by scripts/third-party-licenses.py from the locked dependency
# graph (cargo metadata --format-version 1 --locked --offline). The list has
# two parts, in this order: the components named in NOTICE, then the crates
# that come from a registry. One line per crate:
#
#   <name> <version> (<licence expression>)
#
# A crate without a licence expression is listed as NOASSERTION; the full
# text of each licence is the one the crate itself ships, in its own source
# tree and in its upstream repository.
#
# The crates of this workspace are Auxesis itself, so they are not in this
# list: they are under the Apache-2.0 text in LICENSE. The components named
# in NOTICE are not Rust crates; they keep their own licences, and the list
# starts with them:
#
#   <name>: <licence>
#
# This is the copy published in the repository. Refresh it with
#
#     python3 -I scripts/third-party-licenses.py .
#
# whenever Cargo.lock changes. The app bundle carries its own copy, written
# at package time.
"""


def metadata() -> dict:
    """The workspace metadata, read offline from the locked graph."""
    try:
        result = subprocess.run(METADATA, cwd=ROOT, capture_output=True, text=True, check=False)
    except OSError:
        # No cargo on this machine: say so and stop, with no traceback.
        raise SystemExit("third-party-licenses: cargo not found")
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        raise SystemExit("third-party-licenses: cargo metadata failed")
    return json.loads(result.stdout)


def lines(packages: list[dict]) -> list[str]:
    """One line per crate: name, version, licence expression."""
    rows = sorted((p["name"], p["version"], p.get("license") or "NOASSERTION") for p in packages)
    return [f"{name} {version} ({licence})" for name, version, licence in rows]


def components() -> list[str]:
    """The components NOTICE names, with the licence NOTICE gives each one.

    NOTICE lists them as `- <name>: <licence>`; this keeps that line
    verbatim, so the two files can never drift apart.
    """
    try:
        text = NOTICE.read_text(encoding="utf-8")
    except OSError:
        return []
    rows = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line.startswith("- "):
            continue
        name, separator, licence = line[2:].partition(": ")
        if separator:
            rows.append(f"{name}: {licence}")
    return rows


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: third-party-licenses.py <destination-directory>", file=sys.stderr)
        return 2
    destination = Path(argv[1])
    destination.mkdir(parents=True, exist_ok=True)
    packages = metadata()["packages"]
    # A crate from a registry has a source; the crates of this workspace have
    # none, and they are not third-party, so they stay out of this list.
    registry = [p for p in packages if p.get("source")]
    named = components()
    body = "\n".join(
        [
            "# The components named in NOTICE (not Rust crates)",
            *named,
            "",
            "# The crates of the locked dependency graph that come from a registry",
            *lines(registry),
        ]
    )
    output = destination / FILENAME
    output.write_text(HEADER + body + "\n", encoding="utf-8")
    print(
        f"third-party-licenses: wrote {len(named)} components and "
        f"{len(registry)} crates to {output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
